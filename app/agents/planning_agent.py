"""Module 2: Project Planning Agent.

Consumes the structured requirements specification from Module 1
and generates an actionable engineering project plan with requirement traceability,
task breakdown, dependency scheduling, milestones, and a development roadmap.
"""

from langchain_core.messages import SystemMessage, HumanMessage
from app.schemas import RequirementAnalysis, ProjectPlan
from app.state import BlueprintState
from app.llm import invoke_structured

PLANNING_SYSTEM_PROMPT = """You are a Lead Software Project Planner and Engineering Manager.

Your task is to take a structured Software Requirements Specification (SRS) generated by the Requirement Analysis Agent and synthesize an actionable, high-traceability Software Engineering Project Plan.

IMPORTANT RULES:
1. Do NOT analyze the original raw idea. You MUST strictly base your plan on the provided structured requirements.
2. Requirement Traceability:
   - Every task MUST explicitly link to one or more functional requirement IDs (e.g., ["FR-001"]).
   - Every functional requirement must be covered by at least one development task.
3. Modules:
   - Group related requirements and tasks into cohesive logical modules (e.g. Authentication, Order Processing).
   - Format module IDs strictly as MOD-001, MOD-002, etc.
   - Include mapped requirement_ids and task_ids.
4. Tasks:
   - Format task IDs strictly as T-001, T-002, etc.
   - Provide concrete engineering titles (e.g., "Implement User Registration Endpoint & Hashing").
   - Assign realistic estimated_hours (e.g. 2.0 to 16.0 hours per task).
   - Define prerequisite task dependencies (e.g., ["T-001"]) ensuring a Directed Acyclic Graph (DAG) with NO circular dependencies.
5. Milestones:
   - Group tasks into clear deliverable milestones (format IDs strictly as M-001, M-002, etc.).
   - Examples: "M-001: Foundation & Auth Setup", "M-002: Core Domain Services".
6. Roadmap:
   - Provide an ordered, phased roadmap (e.g., ["Phase 1: Architecture & Auth Foundation", "Phase 2: Core Domain Services", "Phase 3: Integration & Testing", "Phase 4: Deployment & Release"]).

Return the result conforming strictly to the requested JSON schema.
"""


def generate_project_plan(requirements: RequirementAnalysis) -> ProjectPlan:
    """Transform structured RequirementAnalysis into an actionable ProjectPlan."""
    if not requirements or not requirements.functional_requirements:
        raise ValueError("Requirements specification is missing or contains no functional requirements.")

    # Format the input requirements into structured context for the planner
    requirements_json = requirements.model_dump_json(indent=2)

    prompt_content = f"""Synthesize a structured engineering project plan for the following Software Requirements Specification and output a valid JSON object matching this exact schema:

JSON Schema:
{{
  "modules": [
    {{
      "id": "MOD-001",
      "name": "string",
      "description": "string",
      "requirement_ids": ["FR-001"],
      "task_ids": ["T-001"]
    }}
  ],
  "tasks": [
    {{
      "id": "T-001",
      "title": "string",
      "description": "string",
      "requirement_ids": ["FR-001"],
      "priority": "Must",
      "estimated_hours": 4.0,
      "dependencies": []
    }}
  ],
  "milestones": [
    {{
      "id": "M-001",
      "name": "string",
      "description": "string",
      "task_ids": ["T-001"]
    }}
  ],
  "roadmap": [
    "Phase 1: string",
    "Phase 2: string"
  ]
}}

Software Requirements Specification:
{requirements_json}
"""

    messages = [
        SystemMessage(content=PLANNING_SYSTEM_PROMPT),
        HumanMessage(content=prompt_content),
    ]

    return invoke_structured(messages, ProjectPlan)



def planning_agent_node(state: BlueprintState) -> BlueprintState:
    """LangGraph node for Module 2: Project Planning Agent."""
    requirements = state.get("requirements")
    if not requirements:
        errors = list(state.get("errors", []))
        errors.append("PlanningAgent error: No requirements found in state to plan.")
        return {
            **state,
            "errors": errors
        }

    try:
        project_plan = generate_project_plan(requirements)
        return {
            **state,
            "project_plan": project_plan,
        }
    except Exception as e:
        errors = list(state.get("errors", []))
        errors.append(f"PlanningAgent error: {str(e)}")
        return {
            **state,
            "errors": errors
        }
