"""State definition for LangGraph blueprint orchestration."""

from typing import List, Optional
from typing_extensions import TypedDict
from app.schemas import RequirementAnalysis, ProjectPlan


class BlueprintState(TypedDict, total=False):
    """Shared state object passed between LangGraph agent nodes.
    
    Attributes:
        project_idea: The raw user-supplied natural language project description.
        requirements: Structured SRS generated by Module 1 (Requirement Analysis Agent).
        project_plan: Structured development plan generated by Module 2 (Project Planning Agent).
        errors: List of error messages encountered during pipeline execution (if any).
    """
    project_idea: str
    requirements: Optional[RequirementAnalysis]
    project_plan: Optional[ProjectPlan]
    errors: Optional[List[str]]
