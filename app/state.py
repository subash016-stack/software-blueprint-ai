"""State definition for LangGraph blueprint orchestration with multi-module tracking and hashing."""

from typing import Any, Dict, List, Optional
from typing_extensions import TypedDict
from app.schemas import (
    RequirementAnalysis,
    ProjectPlan,
    ArchitectureBlueprint,
    GroundedRecommendation,
    ValidationReport,
    ImpactReport
)


class BlueprintState(TypedDict, total=False):
    """Shared state object passed across all LangGraph agent nodes.
    
    Attributes:
        project_id: Unique identifier of the project.
        project_idea: Raw natural-language project idea.
        requirements: Structured SRS generated by Module 1.
        requirements_hash: Deterministic fingerprint of SRS.
        project_plan: Structured development plan generated by Module 2.
        project_plan_hash: Deterministic fingerprint of Project Plan.
        architecture: Structured architecture blueprint generated by Module 3.
        architecture_hash: Deterministic fingerprint of Architecture.
        rag_recommendations: Evidence-grounded recommendations from Module 4.
        validation_report: Multi-dimensional audit & score from Module 5.
        impact_report: Change impact blast radius analysis from Module 6.
        version: Blueprint version number (e.g. 1, 2).
        errors: Error messages encountered during pipeline execution.
        warnings: Non-fatal pipeline warnings.
        metadata: Execution metadata (timestamps, token stats, timings).
    """
    project_id: str
    project_idea: str
    requirements: Optional[RequirementAnalysis]
    requirements_hash: Optional[str]
    project_plan: Optional[ProjectPlan]
    project_plan_hash: Optional[str]
    architecture: Optional[ArchitectureBlueprint]
    architecture_hash: Optional[str]
    rag_recommendations: Optional[List[GroundedRecommendation]]
    validation_report: Optional[ValidationReport]
    impact_report: Optional[ImpactReport]
    version: Optional[int]
    errors: Optional[List[str]]
    warnings: Optional[List[str]]
    metadata: Optional[Dict[str, Any]]
